-- =============================================================================
-- 5. TRIGGER AUTOMÁTICO AO CRIAR NOVA CONTA NO SUPABASE AUTH
-- =============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.perfis (id, nome, data_nascimento, meta_semanal)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(TRIM(NEW.raw_user_meta_data->>'nome'), ''), 'Usuário'),
    NEW.raw_user_meta_data->>'data_nascimento',
    3
  )
  ON CONFLICT (id) DO UPDATE
    SET nome = EXCLUDED.nome,
        data_nascimento = COALESCE(EXCLUDED.data_nascimento, public.perfis.data_nascimento);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Cria perfil inicial para usuários que já foram cadastrados antes de rodar o script
INSERT INTO public.perfis (id, nome, data_nascimento, meta_semanal)
SELECT
  u.id,
  COALESCE(NULLIF(TRIM(u.raw_user_meta_data->>'nome'), ''), split_part(u.email, '@', 1), 'Usuário'),
  u.raw_user_meta_data->>'data_nascimento',
  3
FROM auth.users u
ON CONFLICT (id) DO NOTHING;

-- 1. TABELA DE PERFIS E CONFIGURAÇÕES DO USUÁRIO
CREATE TABLE IF NOT EXISTS public.perfis (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nome TEXT NOT NULL DEFAULT 'Usuário',
  data_nascimento TEXT,
  meta_semanal INTEGER NOT NULL DEFAULT 3,
  lembretes_ativo BOOLEAN NOT NULL DEFAULT true,
  horario_lembretes TEXT DEFAULT '18:00',
  dias_lembretes TEXT DEFAULT 'Seg, Qua e Sex',
  antecedencia_lembrete INTEGER NOT NULL DEFAULT 30,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. TABELA DE TREINOS (ISOLADA POR USUÁRIO)
CREATE TABLE IF NOT EXISTS public.treinos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  local_id INTEGER NOT NULL,
  nome TEXT NOT NULL,
  data TEXT NOT NULL,
  duracao INTEGER NOT NULL DEFAULT 0,
  grupo_muscular TEXT NOT NULL,
  observacoes TEXT,
  status TEXT NOT NULL DEFAULT 'agendado',
  horario TEXT,
  repetir TEXT DEFAULT 'uma_vez',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_treinos_user_local UNIQUE (user_id, local_id)
);

-- 3. TABELA DE EXERCÍCIOS / SÉRIES (RELAÇÃO 1:N COM TREINOS)
CREATE TABLE IF NOT EXISTS public.exercicios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  treino_local_id INTEGER NOT NULL,
  nome TEXT NOT NULL,
  series INTEGER NOT NULL,
  repeticoes INTEGER NOT NULL,
  carga NUMERIC NOT NULL DEFAULT 0,
  descanso INTEGER,
  concluida INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_exercicios_treino
    FOREIGN KEY (user_id, treino_local_id)
    REFERENCES public.treinos (user_id, local_id)
    ON DELETE CASCADE
);

-- ÍNDICES DE PERFORMANCE
CREATE INDEX IF NOT EXISTS idx_treinos_user_data ON public.treinos (user_id, data);
CREATE INDEX IF NOT EXISTS idx_exercicios_user_treino ON public.exercicios (user_id, treino_local_id);

